"""Deterministic, user-authorized sprite compositing. Originals are read only.
Usage: python scripts/build-parent-portraits.py --source ../../output/imagegen/imom-parent-custom-v1
Requires Pillow and numpy. App output is 512px; export output retains 1024px.
"""
from pathlib import Path
import argparse, json, hashlib
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

APP = Path(__file__).resolve().parents[1]
ROOT = APP.parent.parent
args = argparse.ArgumentParser()
args.add_argument('--source', type=Path, default=ROOT/'output/imagegen/imom-parent-custom-v1')
source = args.parse_args().source.resolve()
dest = APP/'assets/parent-portraits'
export = ROOT/'output/imagegen/imom-parent-custom-v2'
dest.mkdir(parents=True, exist_ok=True)
export.mkdir(parents=True, exist_ok=True)
STATES = ['neutral', 'closed', 'open', 'wide', 'round', 'narrow']
ROIS = {'mother': (452,488,574,558), 'father': (448,500,578,576)}
ANCHORS = {'mother': (513,522), 'father': (513,536)}

def load(path):
    return Image.open(path).convert('RGBA').resize((1024,1024), Image.Resampling.LANCZOS)

def clean(im):
    a = im.getchannel('A')
    solid = a.point(lambda p: 255 if p >= 160 else 0)
    ImageDraw.floodfill(solid, (512,440), 128, thresh=0)
    connected = Image.fromarray(np.where(np.asarray(solid)==128,255,0).astype('uint8'))
    # Remove detached specks and thin edge fringe; no changes to interior artwork.
    connected = connected.filter(ImageFilter.MinFilter(5)).filter(ImageFilter.MaxFilter(5))
    connected = connected.filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(.6))
    pixels = np.asarray(im).copy()
    pixels[:,:,3] = np.minimum(np.asarray(a),np.asarray(connected))
    pixels[pixels[:,:,3]<4] = 0
    return Image.fromarray(pixels)

def mouth_patch(base, frame, roi, amount=1):
    x0,y0,x1,y1=roi;w,h=x1-x0,y1-y0
    patch=frame.crop(roi).convert('RGB')
    # Match surrounding skin tone before feathering inside the bounded mouth ROI.
    bp=np.asarray(base.crop(roi).convert('RGB')).astype(float)
    pp=np.asarray(patch).astype(float)
    ring=np.ones((h,w),dtype=bool);ring[9:-9,9:-9]=False
    delta=np.median(bp[ring]-pp[ring],axis=0)
    patch=Image.fromarray(np.clip(pp+delta,0,255).astype('uint8'))
    if amount != 1:
        # Vertical mouth aperture calibration without scaling the face or head.
        center=(h-1)/2
        patch=patch.transform((w,h),Image.Transform.AFFINE,(1,0,0,0,1/amount,center-center/amount),Image.Resampling.BICUBIC)
    mask=Image.new('L',(w,h));ImageDraw.Draw(mask).rounded_rectangle((5,5,w-6,h-6),radius=18,fill=255)
    mask=mask.filter(ImageFilter.GaussianBlur(3))
    mask_np=np.asarray(mask).copy();mask_np[:2]=0;mask_np[-2:]=0;mask_np[:,:2]=0;mask_np[:,-2:]=0
    result=base.copy();result.paste(patch,(x0,y0),Image.fromarray(mask_np));result.putalpha(base.getchannel('A'))
    return result

def eyes_overlay(base, kind, role):
    # Eye-only overlay, never used for mouth compositing at runtime.
    # Eye centers in the normalized 1024 reference artwork.
    eyes = [(445,407),(581,407)] if role=='mother' else [(443,403),(583,403)]
    overlay=Image.new('RGBA',base.size)
    for cx,cy in eyes:
        box=(cx-40,cy-24,cx+40,cy+25)
        patch=base.crop(box)
        if kind=='blink':
            # Skin sampled from immediately below the eyes; keep lids inside the original eye region.
            skin=base.crop((cx-40,cy+22,cx+40,cy+31)).resize((80,49),Image.Resampling.BICUBIC)
            mask=Image.new('L',(80,49));ImageDraw.Draw(mask).ellipse((4,7,76,46),fill=255)
            mask=mask.filter(ImageFilter.GaussianBlur(3))
            patch=Image.composite(skin,patch,mask)
            draw=ImageDraw.Draw(patch)
            points=[(x,22+6*(1-((x-40)/29)**2)) for x in range(11,70)]
            draw.line(points,fill=(97,60,37,255),width=3)
        else:
            # Smooth horizontal displacement decays at lid corners, so no duplicate pupils.
            arr=np.asarray(patch).copy();out=arr.copy()
            for y in range(10,41):
                for x in range(6,75):
                    weight=max(0,1-((x-40)/35)**2)*max(0,1-((y-25)/16)**2)
                    sx=max(0,min(79,x-int(round(7*weight))))
                    out[y,x]=arr[y,sx]
            patch=Image.fromarray(out)
        mask=Image.new('L',(80,49));ImageDraw.Draw(mask).rounded_rectangle((2,2,77,46),radius=12,fill=255)
        mask=mask.filter(ImageFilter.GaussianBlur(1));patch.putalpha(mask)
        overlay.alpha_composite(patch,(box[0],box[1]))
    return overlay

manifest={'version':2,'canvas':[512,512],'exportCanvas':[1024,1024],'runtime':'full-avatar PNG frame swaps; eye-only blink/gaze overlays','variants':{},'sources':[]}
registry=['// Generated by scripts/build-parent-portraits.py. All Metro requires are static.', "import type { ParentFrame } from '@/lib/parentFrames';", "import type { PortraitId } from '@/lib/portraitConfig';", 'export const PORTRAITS = {']
qa=[];contacts=[]
for role,hairs,outfits in [('mother',['bob','ponytail'],['peach','cardigan']),('father',['sidepart','wavy'],['cream','sage'])]:
    canonical={state:load(APP/f'assets/parent-2d/{state}.png') if role=='mother' else load(source/f'father-sidepart-cream-{state}.png') for state in STATES}
    for hi,hair in enumerate(hairs):
        for oi,outfit in enumerate(outfits):
            vid=f'{role}-{hi}-{oi}';stem=f'{role}-{hair}-{outfit}';original=source/f'{stem}-neutral.png'
            base=clean(load(original));roi=ROIS[role]
            # One canonical neutral mouth also removes any source-specific lip drift.
            neutral=mouth_patch(base,canonical['neutral'],roi)
            manifest['sources'].append({'file':original.name,'sha256':hashlib.sha256(original.read_bytes()).hexdigest()})
            entry={'character':role,'hair':hi,'outfit':oi,'anchor':[v/2 for v in ANCHORS[role]],'mouthRoi':[v/2 for v in roi],'frames':{}}
            registry.append(f"  '{vid}': {{")
            for scale,amount in [('normal',1),('small',.8),('large',1.2)]:
                registry.append(f'    {scale}: {{')
                for state in STATES:
                    frame=neutral if state=='neutral' else mouth_patch(neutral,canonical[state],roi,amount if state not in ['closed'] else 1)
                    filename=f'{vid}-{scale}-{state}.png'
                    # Crop pastes happen BEFORE resizing; outside-ROI equality is verified on final app files.
                    mobile=frame.resize((512,512),Image.Resampling.LANCZOS);mobile.save(dest/filename,optimize=True)
                    registry.append(f"      {state}: require('../../assets/parent-portraits/{filename}'),")
                    if scale=='normal':
                        frame.save(export/f'{stem}-{state}.png',optimize=True)
                        entry['frames'][state]=filename
                        if state=='neutral' or vid in ['mother-0-0','father-0-0']: contacts.append((stem+' '+state,mobile))
                        # Allow 3px filter support around the scaled ROI.
                        out=np.any(np.asarray(mobile)!=np.asarray(neutral.resize((512,512),Image.Resampling.LANCZOS)),axis=2)
                        x0,y0,x1,y1=[int(v/2) for v in roi];out[max(0,y0-3):y1+3,max(0,x0-3):x1+3]=False
                        qa.append({'file':filename,'outsideMouthChangedPixels':int(out.sum())})
                registry.append('    },')
            for kind in ['blink','right']:
                overlay=eyes_overlay(neutral,kind,role).resize((512,512),Image.Resampling.LANCZOS)
                filename=f'{vid}-{kind}.png';overlay.save(dest/filename,optimize=True)
                registry.append(f"    {kind}: require('../../assets/parent-portraits/{filename}'),")
            registry.append(f'    anchor: [{ANCHORS[role][0]/1024}, {ANCHORS[role][1]/1024}],')
            registry.append('  },');manifest['variants'][vid]=entry
registry.append('} satisfies Record<PortraitId, Record<\'normal\' | \'small\' | \'large\', Record<ParentFrame, number>> & { blink: number; right: number; anchor: number[] }>;')
(APP/'src/lib/portraitAssets.ts').write_text('\n'.join(registry)+'\n',encoding='utf-8')
